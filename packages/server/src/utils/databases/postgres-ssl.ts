import net from "node:net";
import { quote } from "shell-quote";

export const POSTGRES_SSL_MOUNT_PATH = "/etc/postgres/ssl";

export type PostgresSslMode = "disabled" | "optional" | "required";

export interface PostgresSslArgsInput {
	command?: string | null;
	args?: string[] | null;
	sslMode: PostgresSslMode;
}

export const buildPostgresSslArgs = ({
	command,
	args,
	sslMode,
}: PostgresSslArgsInput): string[] | undefined => {
	// A custom command replaces the whole container invocation (entrypoint +
	// cmd), so SSL flags cannot be appended safely there: the user owns them.
	if (sslMode === "disabled" || (command && command.trim() !== "")) {
		return undefined;
	}
	const sslArgs = [
		"-c",
		"ssl=on",
		"-c",
		`ssl_cert_file=${POSTGRES_SSL_MOUNT_PATH}/server.crt`,
		"-c",
		`ssl_key_file=${POSTGRES_SSL_MOUNT_PATH}/server.key`,
	];
	if (sslMode === "required") {
		sslArgs.push("-c", `hba_file=${POSTGRES_SSL_MOUNT_PATH}/pg_hba.conf`);
	}
	// Args alone keep the image entrypoint (docker-entrypoint.sh) intact, so
	// first-boot initialization still runs before postgres starts.
	const base = args && args.length > 0 ? args : ["postgres"];
	return [...base, ...sslArgs];
};

export const getSslCertMount = (sslDir: string) => ({
	Type: "bind" as const,
	Source: sslDir,
	Target: POSTGRES_SSL_MOUNT_PATH,
});

// `md5` is used as the TCP auth method on purpose: PostgreSQL automatically
// performs SCRAM when the stored secret is SCRAM-encrypted, while legacy
// MD5-stored passwords keep working (they would fail under scram-sha-256).
export const buildPostgresSslHba = () =>
	[
		"# Generated by Dokploy (sslMode=required): TLS-only TCP connections",
		"local all all trust",
		"host all all 127.0.0.1/32 trust",
		"host all all ::1/128 trust",
		"hostssl all all all md5",
		"",
	].join("\n");

export const buildPostgresSslSan = ({
	appName,
	serverIp,
}: {
	appName: string;
	serverIp?: string | null;
}) =>
	[
		`DNS:${appName}`,
		"DNS:localhost",
		"IP:127.0.0.1",
		...(serverIp
			? [net.isIP(serverIp) ? `IP:${serverIp}` : `DNS:${serverIp}`]
			: []),
	].join(",");

export const buildPostgresSslCertScript = ({
	sslDir,
	san,
	appName,
	required,
}: {
	sslDir: string;
	san: string;
	appName: string;
	required: boolean;
}) => {
	const hba = buildPostgresSslHba();
	return `set -e
SSL_DIR=${quote([sslDir])}
SAN=${quote([san])}
CA_CN=${quote([`${appName}-ca`])}
SERVER_CN=${quote([appName])}
mkdir -p "$SSL_DIR"
if [ ! -f "$SSL_DIR/server.crt" ] || [ ! -f "$SSL_DIR/server.key" ] || [ ! -f "$SSL_DIR/ca.crt" ]; then
	openssl req -x509 -newkey rsa:2048 -nodes -keyout "$SSL_DIR/ca.key" -out "$SSL_DIR/ca.crt" -days 3650 -subj "/CN=$CA_CN"
	openssl req -newkey rsa:2048 -nodes -keyout "$SSL_DIR/server.key" -out "$SSL_DIR/server.csr" -subj "/CN=$SERVER_CN"
	printf "subjectAltName=%s\\n" "$SAN" > "$SSL_DIR/server.ext"
	openssl x509 -req -in "$SSL_DIR/server.csr" -CA "$SSL_DIR/ca.crt" -CAkey "$SSL_DIR/ca.key" -CAcreateserial -out "$SSL_DIR/server.crt" -days 3650 -extfile "$SSL_DIR/server.ext"
	rm -f "$SSL_DIR/server.csr" "$SSL_DIR/server.ext" "$SSL_DIR/ca.key"
fi
${
	required
		? `cat > "$SSL_DIR/pg_hba.conf" <<'DOKPLOY_PG_HBA'
${hba}DOKPLOY_PG_HBA
`
		: ""
}chmod 600 "$SSL_DIR"/*.key
chmod 644 "$SSL_DIR"/*.crt
cat "$SSL_DIR/ca.crt"
`;
};
